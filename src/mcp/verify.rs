//! Translate every candidate; let F* validate individual checked proof dependencies.

use std::collections::{BTreeMap, BTreeSet};
use std::fs::{self, File};
use std::io::Read;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::{
    Arc,
    atomic::{AtomicBool, Ordering},
};

use moka::future::Cache;
use sha2::{Digest, Sha256};
use tokio::sync::Semaphore;

use super::diagnostics::{self, Diagnostics};
use super::navigation::SemanticIndex;
use super::process::{self, Cancellation};
use super::workspace::{Failure, Result, Snapshot, Toolchain};

#[derive(Clone)]
pub struct Progress(Arc<dyn Fn(&str, &str) + Send + Sync>);

impl Progress {
    pub fn new(callback: impl Fn(&str, &str) + Send + Sync + 'static) -> Self {
        Self(Arc::new(callback))
    }
    fn publish(&self, phase: &str, message: &str) {
        (self.0)(phase, message);
    }
}
#[derive(Clone, Copy, Debug, Eq, Hash, PartialEq)]
struct VerificationKey([u8; 32]);

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
struct VerificationContext([u8; 32]);

#[derive(Debug, Eq, PartialEq)]
struct ArtifactChecksum([u8; 32]);

/// Exact generated bytes, shared as one immutable manifest by accepted proofs.
#[derive(Debug)]
struct GeneratedSources(BTreeMap<String, Vec<u8>>);

impl std::ops::Deref for GeneratedSources {
    type Target = BTreeMap<String, Vec<u8>>;

    fn deref(&self) -> &Self::Target {
        &self.0
    }
}

#[derive(Debug)]
pub struct VerifiedArtifacts {
    // The accepted session and the bounded LRU pin this lifetime independently.
    storage: Arc<tempfile::TempDir>,
    context: VerificationContext,
    generated: Arc<GeneratedSources>,
    checked: BTreeMap<String, ArtifactChecksum>,
}

impl VerifiedArtifacts {
    pub fn validate(&self) -> Result<()> {
        for (name, expected) in &self.checked {
            let actual = ArtifactChecksum::read(&self.directory().join(name)).map_err(|error| {
                Failure::new(
                    "proof_cache_lost",
                    format!(
                        "required checked artifact {name} is unavailable: {}",
                        error.message.replace(
                            self.storage.path().to_string_lossy().as_ref(),
                            "<proof-cache>"
                        )
                    ),
                )
            })?;
            if &actual != expected {
                return Err(Failure::new(
                    "proof_cache_lost",
                    format!("required checked artifact {name} was modified"),
                ));
            }
        }
        Ok(())
    }

    fn directory(&self) -> PathBuf {
        self.storage.path().join("checked")
    }

    fn seed(&self, snapshot: &Snapshot, manifest: &GeneratedSources) -> Result<()> {
        self.validate()?;
        for (name, _) in &self.checked {
            let source_name = name.strip_suffix(".checked").ok_or_else(|| {
                Failure::new("proof_cache_lost", "invalid checked artifact manifest")
            })?;
            // Removed implementations/interfaces must never remain discoverable.
            if !manifest.contains_key(source_name) || !self.generated.contains_key(source_name) {
                continue;
            }
            let source = self.directory().join(name);
            let target = snapshot.checked().join(name);
            if fs::hard_link(&source, &target).is_err() {
                fs::copy(&source, &target).map_err(|error| {
                    Failure::new(
                        "worker_failed",
                        format!("cannot copy checked artifact {name}: {error}"),
                    )
                })?;
            }
        }
        Ok(())
    }
}

pub struct VerificationResult {
    pub artifacts: Option<Arc<VerifiedArtifacts>>,
    pub diagnostics: Diagnostics,
    pub cache_hit: bool,
    pub failure: Option<Failure>,
}

pub struct Verifier {
    pub toolchain: Toolchain,
    fstar: PathBuf,
    pulse: PathBuf,
    cache: Cache<VerificationKey, Arc<VerifiedArtifacts>>,
    // ponytail: one verifier job at a time; raise concurrency only after measuring solver memory.
    pub gate: Arc<Semaphore>,
}

impl Verifier {
    pub fn new(toolchain: Toolchain, executable: PathBuf, pulse: PathBuf) -> Result<Self> {
        let fstar = resolve_executable(&executable)?;
        let pulse = fs::canonicalize(&pulse).map_err(|error| {
            Failure::new(
                "toolchain_unavailable",
                format!("cannot open Pulse library: {error}"),
            )
        })?;
        if !pulse.join("Pulse.Lib.C.fsti").is_file()
            || !pulse.join("_cache/Pulse.Lib.C.fsti.checked").is_file()
        {
            return Err(Failure::new(
                "toolchain_unavailable",
                "Pulse support library is missing; run env -u ADMIT -u OTHERFLAGS make -C pulse, or select --pulse-dir",
            ));
        }
        let library =
            fs::canonicalize(command_text(&fstar, &["--locate_lib"])?).map_err(|error| {
                Failure::new(
                    "toolchain_unavailable",
                    format!("cannot open F* library: {error}"),
                )
            })?;
        if !library.is_dir() {
            return Err(Failure::new(
                "toolchain_unavailable",
                "F* --locate_lib did not return a library directory",
            ));
        }
        command_text(&fstar, &["--version"])?;
        Ok(Self {
            toolchain,
            fstar,
            pulse,
            cache: Cache::builder()
                .max_capacity(32)
                .eviction_policy(moka::policy::EvictionPolicy::lru())
                .build(),
            gate: Arc::new(Semaphore::new(1)),
        })
    }

    /// Caller owns the server-wide permit from preparation through final publication.
    pub async fn verify(
        &self,
        snapshot: Arc<Snapshot>,
        index: Arc<SemanticIndex>,
        accepted: Option<Arc<VerifiedArtifacts>>,
        cancel: Cancellation,
        progress: Progress,
        status_uri: &str,
    ) -> VerificationResult {
        let mut diagnostics = index.diagnostics.clone();
        let result = self
            .run(
                &snapshot,
                &index,
                accepted,
                &cancel,
                &progress,
                status_uri,
                &mut diagnostics,
            )
            .await;
        match result {
            Ok((artifacts, cache_hit)) => VerificationResult {
                artifacts: Some(artifacts),
                diagnostics,
                cache_hit,
                failure: None,
            },
            Err(failure) => VerificationResult {
                artifacts: None,
                diagnostics,
                cache_hit: false,
                failure: Some(failure),
            },
        }
    }

    async fn run(
        &self,
        snapshot: &Arc<Snapshot>,
        index: &Arc<SemanticIndex>,
        accepted: Option<Arc<VerifiedArtifacts>>,
        cancel: &Cancellation,
        progress: &Progress,
        status_uri: &str,
        diagnostics: &mut Diagnostics,
    ) -> Result<(Arc<VerifiedArtifacts>, bool)> {
        cancel.check()?;
        if let Some(failure) = &index.failure {
            return Err(failure.clone());
        }
        progress.publish("translating", "translating frozen candidate sources");
        let mut arguments = vec![
            "--quiet".to_owned(),
            "--outdir".to_owned(),
            path_string(&snapshot.out())?,
        ];
        arguments.extend(
            snapshot
                .roots
                .iter()
                .map(|path| path_string(path))
                .collect::<Result<Vec<_>>>()?,
        );
        let output_progress = progress.clone();
        let translated = process::run(
            &std::env::current_exe().map_err(worker_error)?,
            &arguments,
            &snapshot.root,
            cancel,
            process::Output::new(move |line| output_progress.publish("translating", &line)),
        )
        .await?;
        cancel.check()?;
        let metadata = match diagnostics::translation(snapshot, index, status_uri) {
            Ok(metadata) => metadata,
            Err(failure) => {
                let raw = format!(
                    "{}\n{}\n{}",
                    failure.message,
                    String::from_utf8_lossy(&translated.stdout),
                    String::from_utf8_lossy(&translated.stderr)
                );
                let message = raw.replace(
                    snapshot.storage.path().to_string_lossy().as_ref(),
                    "<candidate>",
                );
                let mut diagnostic =
                    lsp_types::Diagnostic::new_simple(lsp_types::Range::default(), message);
                diagnostic.severity = Some(lsp_types::DiagnosticSeverity::ERROR);
                diagnostic.source = Some("PAL".to_owned());
                diagnostics
                    .entry(status_uri.to_owned())
                    .or_default()
                    .push(diagnostic);
                return Err(Failure::new(
                    "translation_failed",
                    "PAL did not produce valid diagnostics and source metadata",
                ));
            }
        };
        diagnostics::merge(diagnostics, metadata.diagnostics.clone());
        if !translated.status.success() || diagnostics::has_errors(diagnostics) {
            if !translated.status.success() {
                diagnostics::merge(
                    diagnostics,
                    diagnostics::fstar(
                        snapshot,
                        &metadata,
                        &translated.stdout,
                        &translated.stderr,
                        status_uri,
                        false,
                    ),
                );
            }
            return Err(Failure::new(
                "translation_failed",
                "PAL translation failed; see diagnostics",
            ));
        }
        let sources = Arc::new(GeneratedSources::read(snapshot)?);
        if let Some(previous) = &accepted {
            previous.validate()?;
        }
        snapshot.recheck_inputs()?;
        let context = self.context().await?;
        let key = VerificationKey::new(&sources, context);
        progress.publish(
            "verifying",
            "validating generated proof units and checked dependencies",
        );
        let computed = AtomicBool::new(false);
        let checked = self
            .cache
            .try_get_with(key, async {
                computed.store(true, Ordering::Relaxed);
                cancel.check()?;
                // A changed toolchain/library context starts a completely empty namespace.
                if let Some(previous) = accepted
                    .as_ref()
                    .filter(|previous| previous.context == context)
                {
                    previous.seed(snapshot, &sources)?;
                }
                remove_stale_checked(snapshot, &sources)?;
                // F* writes caches only for explicitly listed roots. Check all interfaces,
                // types, globals and pure functions together before isolated implementations.
                // Listing an implementation alongside its caller would expose its interface.
                let mut signatures = Vec::new();
                let mut implementations = Vec::new();
                let mut filenames = sources.keys().map(String::as_str).peekable();
                while let Some(name) = filenames.next() {
                    // Sorted .fst/.fsti pairs are adjacent; pairing needs no dependency graph.
                    if name.ends_with(".fst")
                        && filenames
                            .peek()
                            .is_some_and(|next| next.strip_suffix('i') == Some(name))
                    {
                        implementations.push(name);
                    } else {
                        signatures.push(name);
                    }
                }
                let batches = std::iter::once(signatures.as_slice())
                    .chain(implementations.iter().map(std::slice::from_ref));
                for names in batches {
                    let arguments = self.arguments(snapshot, names)?;
                    let output_progress = progress.clone();
                    let output = process::run(
                        &self.fstar,
                        &arguments,
                        &snapshot.out(),
                        cancel,
                        process::Output::new(move |line| {
                            output_progress.publish("verifying", &line)
                        }),
                    )
                    .await?;
                    let issues = diagnostics::fstar(
                        snapshot,
                        &metadata,
                        &output.stdout,
                        &output.stderr,
                        status_uri,
                        output.status.success(),
                    );
                    let errors = diagnostics::has_errors(&issues);
                    diagnostics::merge(diagnostics, issues);
                    cancel.check()?;
                    if !output.status.success() || errors {
                        return Err(Failure::new(
                            "verification_failed",
                            "F* rejected the candidate; see diagnostics",
                        ));
                    }
                }
                let checked = checked_manifest(snapshot, &sources)?;
                self.recheck(snapshot, context, cancel).await?;
                Ok(Arc::new(VerifiedArtifacts {
                    storage: Arc::clone(&snapshot.storage),
                    context,
                    generated: Arc::clone(&sources),
                    checked,
                }))
            })
            .await
            .map_err(|error: Arc<Failure>| (*error).clone())?;
        let hit = !computed.load(Ordering::Relaxed);
        if let Err(error) = checked.validate() {
            self.cache.invalidate(&key).await;
            return Err(error);
        }
        // Also recheck exact-result hits: their proofs are reusable, their source bytes are new.
        if let Err(error) = self.recheck(snapshot, context, cancel).await {
            self.cache.invalidate(&key).await;
            return Err(error);
        }
        Ok((checked, hit))
    }

    fn arguments(&self, snapshot: &Snapshot, names: &[&str]) -> Result<Vec<String>> {
        let mut args = verification_options(
            &path_string(&self.pulse)?,
            &path_string(&snapshot.out())?,
            &path_string(&snapshot.checked())?,
        );
        args.extend(
            names
                .iter()
                .map(|name| path_string(&snapshot.out().join(name)))
                .collect::<Result<Vec<_>>>()?,
        );
        Ok(args)
    }

    async fn context(&self) -> Result<VerificationContext> {
        let fstar = self.fstar.clone();
        let pulse = self.pulse.clone();
        tokio::task::spawn_blocking(move || {
            let mut hash = Sha256::new();
            field(
                &mut hash,
                b"native-signatures-before-isolated-implementations",
            );
            let version = command_text(&fstar, &["--version"])?;
            let library =
                fs::canonicalize(command_text(&fstar, &["--locate_lib"])?).map_err(worker_error)?;
            for item in [path_string(&fstar)?, version, path_string(&library)?] {
                field(&mut hash, item.as_bytes());
            }
            for option in verification_options(&path_string(&pulse)?, "$OUT", "$CHECKED") {
                field(&mut hash, option.as_bytes());
            }
            field(&mut hash, &ArtifactChecksum::read(&fstar)?.0);
            field(&mut hash, b"working-directory=$OUT");
            let mut visited = BTreeSet::new();
            for root in [&pulse, &library] {
                let expanded = command_text(&fstar, &["--expand_include", &path_string(root)?])?;
                for include in expanded.lines() {
                    match fs::canonicalize(include) {
                        Ok(include) => {
                            field(&mut hash, path_string(&include)?.as_bytes());
                            fingerprint_tree(&include, &include, &mut visited, &mut hash)?;
                        }
                        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                            // Installed F* lists optional absent directories, e.g. ulib/legacy.
                            field(&mut hash, include.as_bytes());
                            field(&mut hash, b"absent-include-directory");
                        }
                        Err(error) => {
                            return Err(Failure::new(
                                "verification_context_changed",
                                format!("cannot fingerprint F* include {include:?}: {error}"),
                            ));
                        }
                    }
                }
            }
            Ok(VerificationContext(hash.finalize().into()))
        })
        .await
        .map_err(|error| {
            Failure::new(
                "worker_failed",
                format!("verification context worker failed: {error}"),
            )
        })?
        .map_err(|error| Failure::new("verification_context_changed", error.message))
    }

    async fn recheck(
        &self,
        snapshot: &Snapshot,
        expected: VerificationContext,
        cancel: &Cancellation,
    ) -> Result<()> {
        cancel.check()?;
        snapshot.recheck_inputs()?;
        if self
            .context()
            .await
            .map_err(|error| Failure::new("verification_context_changed", error.message))?
            != expected
        {
            return Err(Failure::new(
                "verification_context_changed",
                "F* executable or library contents changed during verification",
            ));
        }
        snapshot.recheck_inputs()?;
        cancel.check()
    }
}

fn verification_options(pulse: &str, out: &str, checked: &str) -> Vec<String> {
    [
        "--cache_checked_modules",
        "--cache_dir",
        checked,
        "--already_cached",
        "Prims,FStar,Pulse.Nolib,Pulse.Class,Pulse.Lib,PulseCore",
        "--include",
        pulse,
        "--include",
        out,
        "--message_format",
        "json",
        "--ext",
        "fly_deps=false",
    ]
    .into_iter()
    .map(str::to_owned)
    .collect()
}

impl GeneratedSources {
    fn read(snapshot: &Snapshot) -> Result<Self> {
        let mut manifest = BTreeMap::new();
        for entry in fs::read_dir(snapshot.out()).map_err(worker_error)? {
            let entry = entry.map_err(worker_error)?;
            let path = entry.path();
            if matches!(
                path.extension().and_then(|ext| ext.to_str()),
                Some("fst" | "fsti")
            ) {
                let name = entry.file_name().into_string().map_err(|_| {
                    Failure::new("translation_failed", "generated module name is not UTF-8")
                })?;
                let bytes = fs::read(path).map_err(worker_error)?;
                std::str::from_utf8(&bytes).map_err(|_| {
                    Failure::new("translation_failed", "generated proof source is not UTF-8")
                })?;
                manifest.insert(name, bytes);
            }
        }
        if !manifest.contains_key("TranslationErrors.fst") {
            return Err(Failure::new(
                "translation_failed",
                "PAL did not emit the complete generated-source manifest",
            ));
        }
        Ok(Self(manifest))
    }
}

impl VerificationKey {
    fn new(manifest: &GeneratedSources, context: VerificationContext) -> Self {
        let mut hash = Sha256::new();
        field(&mut hash, &context.0);
        for (name, code) in manifest.iter() {
            field(&mut hash, name.as_bytes());
            field(&mut hash, code);
        }
        Self(hash.finalize().into())
    }
}

fn checked_manifest(
    snapshot: &Snapshot,
    sources: &GeneratedSources,
) -> Result<BTreeMap<String, ArtifactChecksum>> {
    sources
        .keys()
        .map(|name| {
            let checked = format!("{name}.checked");
            let digest =
                ArtifactChecksum::read(&snapshot.checked().join(&checked)).map_err(|error| {
                    Failure::new(
                        "verification_failed",
                        format!(
                            "F* did not produce required checked artifact {checked}: {}",
                            error.message
                        ),
                    )
                })?;
            Ok((checked, digest))
        })
        .collect()
}

fn remove_stale_checked(snapshot: &Snapshot, manifest: &GeneratedSources) -> Result<()> {
    for entry in fs::read_dir(snapshot.checked()).map_err(worker_error)? {
        let entry = entry.map_err(worker_error)?;
        if let Some(source) = entry
            .file_name()
            .to_str()
            .and_then(|name| name.strip_suffix(".checked"))
        {
            if !manifest.contains_key(source) {
                fs::remove_file(entry.path()).map_err(worker_error)?;
            }
        }
    }
    Ok(())
}

fn field(hash: &mut Sha256, bytes: &[u8]) {
    hash.update((bytes.len() as u64).to_le_bytes());
    hash.update(bytes);
}

impl ArtifactChecksum {
    fn read(path: &Path) -> Result<Self> {
        let mut file = File::open(path).map_err(|error| {
            Failure::new(
                "worker_failed",
                format!("cannot read {}: {error}", path.display()),
            )
        })?;
        let mut hash = Sha256::new();
        let mut buffer = [0; 65536];
        loop {
            let size = file.read(&mut buffer).map_err(worker_error)?;
            if size == 0 {
                break;
            }
            hash.update(&buffer[..size]);
        }
        Ok(Self(hash.finalize().into()))
    }
}

fn fingerprint_tree(
    root: &Path,
    path: &Path,
    visited: &mut BTreeSet<PathBuf>,
    hash: &mut Sha256,
) -> Result<()> {
    let canonical = fs::canonicalize(path).map_err(|error| {
        Failure::new(
            "verification_context_changed",
            format!(
                "cannot resolve verification context {}: {error}",
                path.display()
            ),
        )
    })?;
    // Follow library symlinks, but terminate cycles and hash each real object once.
    field(
        hash,
        path.strip_prefix(root)
            .unwrap_or(path)
            .to_string_lossy()
            .as_bytes(),
    );
    if !visited.insert(canonical.clone()) {
        field(hash, path_string(&canonical)?.as_bytes());
        return Ok(());
    }
    let metadata = fs::metadata(&canonical).map_err(worker_error)?;
    if metadata.is_dir() {
        field(hash, b"directory");
        let mut entries = fs::read_dir(path)
            .map_err(worker_error)?
            .collect::<std::io::Result<Vec<_>>>()
            .map_err(worker_error)?;
        entries.sort_by_key(|entry| entry.file_name());
        for entry in entries {
            fingerprint_tree(root, &entry.path(), visited, hash)?;
        }
    } else if metadata.is_file() {
        field(hash, b"file");
        field(hash, &ArtifactChecksum::read(&canonical)?.0);
    } else {
        return Err(Failure::new(
            "verification_context_changed",
            "verification library contains a non-regular object",
        ));
    }
    Ok(())
}

fn resolve_executable(path: &Path) -> Result<PathBuf> {
    if path.components().count() > 1 || path.is_absolute() {
        return fs::canonicalize(path).map_err(|error| {
            Failure::new(
                "toolchain_unavailable",
                format!("cannot locate F* executable: {error}"),
            )
        });
    }
    for directory in std::env::split_paths(&std::env::var_os("PATH").unwrap_or_default()) {
        let candidate = directory.join(path);
        if candidate.is_file() {
            return fs::canonicalize(candidate).map_err(worker_error);
        }
    }
    Err(Failure::new(
        "toolchain_unavailable",
        format!("F* executable {} was not found on PATH", path.display()),
    ))
}

fn command_text(executable: &Path, arguments: &[&str]) -> Result<String> {
    let output = Command::new(executable)
        .args(arguments)
        .output()
        .map_err(|error| {
            Failure::new(
                "toolchain_unavailable",
                format!(
                    "cannot run {} {}: {error}",
                    executable.display(),
                    arguments.join(" ")
                ),
            )
        })?;
    if !output.status.success() {
        return Err(Failure::new(
            "toolchain_unavailable",
            format!(
                "{} {} failed: {}",
                executable.display(),
                arguments.join(" "),
                String::from_utf8_lossy(&output.stderr)
            ),
        ));
    }
    let value = String::from_utf8(output.stdout)
        .map_err(|_| Failure::new("toolchain_unavailable", "tool output is not UTF-8"))?;
    let value = value.trim();
    if value.is_empty() {
        return Err(Failure::new(
            "toolchain_unavailable",
            format!("{} returned no output", arguments.join(" ")),
        ));
    }
    Ok(value.to_owned())
}

fn path_string(path: &Path) -> Result<String> {
    path.to_str()
        .map(str::to_owned)
        .ok_or_else(|| Failure::new("invalid_path", "compiler paths must be UTF-8"))
}

fn worker_error(error: std::io::Error) -> Failure {
    Failure::new("worker_failed", error.to_string())
}
